//! Canonical node property names.
//!
//! `SPAWN_PROPS` is the set a `BNOD` descriptor may carry; the JS runtime
//! fetches it from the host so creation-time validation cannot drift from the
//! Rust decoder. `DEFERRED_PROPS` are accepted on the JSX element but applied
//! as `SetProp` ops immediately after `Spawn`, which keeps the descriptor
//! stable while the style surface grows. `padding`, `margin`, and `inset`
//! arrays are split into their edge properties by the JS runtime.
//!
//! `SET_PROPS` is the set `Shell::set_prop` accepts at runtime.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Prop {
    Color,
    BackgroundColor,
    Radius,
    Opacity,
    FontSize,
    PaddingLeft,
    PaddingRight,
    PaddingTop,
    PaddingBottom,
    Width,
    Height,
    FlexGrow,
    FlexShrink,
    ScrollX,
    ScrollY,
    Overflow,
    Row,
    LineHeight,
    TextAlign,
    FontWeight,
    MarginLeft,
    MarginRight,
    MarginTop,
    MarginBottom,
    Gap,
    AlignItems,
    JustifyContent,
    Position,
    Top,
    Right,
    Bottom,
    Left,
    Src,
    Fit,
    ScrollChainX,
    ScrollChainY,
}

impl Prop {
    pub fn parse(key: &str) -> Option<Self> {
        Some(match key {
            "color" => Self::Color,
            "backgroundColor" => Self::BackgroundColor,
            "radius" => Self::Radius,
            "opacity" => Self::Opacity,
            "fontSize" => Self::FontSize,
            "paddingLeft" => Self::PaddingLeft,
            "paddingRight" => Self::PaddingRight,
            "paddingTop" => Self::PaddingTop,
            "paddingBottom" => Self::PaddingBottom,
            "width" => Self::Width,
            "height" => Self::Height,
            "flexGrow" => Self::FlexGrow,
            "flexShrink" => Self::FlexShrink,
            "overflowX" => Self::ScrollX,
            "overflowY" => Self::ScrollY,
            "overflow" => Self::Overflow,
            "flexDirection" => Self::Row,
            "lineHeight" => Self::LineHeight,
            "textAlign" => Self::TextAlign,
            "fontWeight" => Self::FontWeight,
            "marginLeft" => Self::MarginLeft,
            "marginRight" => Self::MarginRight,
            "marginTop" => Self::MarginTop,
            "marginBottom" => Self::MarginBottom,
            "gap" => Self::Gap,
            "alignItems" => Self::AlignItems,
            "justifyContent" => Self::JustifyContent,
            "position" => Self::Position,
            "top" => Self::Top,
            "right" => Self::Right,
            "bottom" => Self::Bottom,
            "left" => Self::Left,
            "src" => Self::Src,
            "fit" => Self::Fit,
            "overscrollX" => Self::ScrollChainX,
            "overscrollY" => Self::ScrollChainY,
            _ => return None,
        })
    }
}

