use crate::Schema;

/// `Prop` enum and `Prop::parse`, in shell-prop order.
pub fn generate(schema: &Schema) -> String {
    let mut out = String::from("// Generated by bubble-schema. Do not edit.\n\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    out.push_str("pub enum Prop {\n");
    for prop in schema.shell_props() {
        out.push_str("    ");
        out.push_str(prop.variant);
        out.push_str(",\n");
    }
    out.push_str("}\n\n");
    out.push_str("impl Prop {\n");
    out.push_str("    pub fn parse(key: &str) -> Option<Self> {\n");
    out.push_str("        Some(match key {\n");
    for prop in schema.shell_props() {
        out.push_str("            \"");
        out.push_str(prop.key);
        out.push_str("\" => Self::");
        out.push_str(prop.variant);
        out.push_str(",\n");
    }
    out.push_str("            _ => return None,\n");
    out.push_str("        })\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    out
}
