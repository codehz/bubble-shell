use crate::{PropType, Schema};

/// Compiler `PropType`, `PrimSpec`, and `prim_spec`.
///
/// Included into `bubble_compiler::props`, which already imports `HashMap`
/// and `LazyLock`. `Ref` lowers to `Unknown` and event handlers to
/// `Function`, matching the previous hand-written tables.
pub fn generate(schema: &Schema) -> String {
    let mut out = String::from("// Generated by bubble-schema. Do not edit.\n\n");
    out.push_str(
        r#"#[derive(Debug, Clone, PartialEq)]
pub(crate) enum PropType {
    Unknown,
    Number,
    String,
    Boolean,
    /// CSS color string or numeric `0xAARRGGBB`.
    Color,
    /// Number, percent string, or `"auto"`.
    Len,
    Function,
    Array(Box<PropType>),
    /// String literal, kept so enum props can reject unknown spellings.
    StrLit(String),
    Union(Vec<&'static str>),
}

impl PropType {
    pub(crate) fn display(&self) -> String {
        match self {
            PropType::Unknown => "unknown".into(),
            PropType::Number => "number".into(),
            PropType::String | PropType::StrLit(_) => "string".into(),
            PropType::Boolean => "boolean".into(),
            PropType::Color => "color".into(),
            PropType::Len => "length".into(),
            PropType::Function => "function".into(),
            PropType::Array(inner) => format!("{}[]", inner.display()),
            PropType::Union(variants) => variants.join(" | "),
        }
    }
}

pub(crate) struct PrimSpec {
    pub(crate) allowed: HashMap<&'static str, PropType>,
    pub(crate) required: &'static [&'static str],
}

"#,
    );

    for prim in schema.primitives() {
        out.push_str("static ");
        out.push_str(&static_name(prim.name));
        out.push_str(": LazyLock<PrimSpec> = LazyLock::new(|| PrimSpec {\n");
        out.push_str("    allowed: HashMap::from([\n");
        for prop in &prim.props {
            out.push_str("        (\"");
            out.push_str(prop.name);
            out.push_str("\", ");
            out.push_str(&rust_prop_type(&prop.ty));
            out.push_str("),\n");
        }
        out.push_str("    ]),\n");
        out.push_str("    required: ");
        out.push_str(&rust_str_slice(&prim.required_props()));
        out.push_str(",\n});\n\n");
    }

    out.push_str("pub(crate) fn prim_spec(tag: &str) -> Option<&'static PrimSpec> {\n");
    out.push_str("    match tag {\n");
    for prim in schema.primitives() {
        out.push_str("        \"");
        out.push_str(prim.name);
        out.push_str("\" => Some(&");
        out.push_str(&static_name(prim.name));
        out.push_str("),\n");
    }
    out.push_str("        _ => None,\n");
    out.push_str("    }\n}\n");
    out
}

fn static_name(name: &str) -> String {
    let mut out = String::new();
    for (index, ch) in name.chars().enumerate() {
        if ch.is_uppercase() && index > 0 {
            out.push('_');
        }
        out.push(ch.to_ascii_uppercase());
    }
    out
}

fn rust_str_slice(items: &[&str]) -> String {
    if items.is_empty() {
        return "&[]".to_string();
    }
    let body = items
        .iter()
        .map(|item| format!("\"{item}\""))
        .collect::<Vec<_>>()
        .join(", ");
    format!("&[{body}]")
}

fn rust_prop_type(ty: &PropType) -> String {
    match ty {
        PropType::Color => "PropType::Color".to_string(),
        PropType::Len => "PropType::Len".to_string(),
        PropType::Number => "PropType::Number".to_string(),
        PropType::String => "PropType::String".to_string(),
        PropType::Boolean => "PropType::Boolean".to_string(),
        PropType::Unknown | PropType::Ref => "PropType::Unknown".to_string(),
        PropType::EventFn(_) | PropType::Func(_) => "PropType::Function".to_string(),
        PropType::Edges => "PropType::Union(vec![\"number\", \"number[]\"])".to_string(),
        PropType::Array(inner) => {
            format!("PropType::Array(Box::new({}))", rust_prop_type(inner))
        }
        PropType::Union(parts) => {
            let mut literals = Vec::with_capacity(parts.len());
            for part in parts {
                match part {
                    PropType::StrLit(text) => literals.push(*text),
                    other => panic!("compiler union only supports string literals, got {other:?}"),
                }
            }
            let body = literals
                .iter()
                .map(|text| format!("\"{text}\""))
                .collect::<Vec<_>>()
                .join(", ");
            format!("PropType::Union(vec![{body}])")
        }
        other => panic!("not a JSX prop type: {other:?}"),
    }
}
