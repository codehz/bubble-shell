use std::io::{self, Write};

fn main() -> io::Result<()> {
    let schema = bubble_schema::bubble_shell_schema();
    let generated = bubble_schema::codegen::dts::generate(&schema);
    let hand_written = include_str!("../hand-written.d.ts");
    let mut out = io::stdout().lock();
    out.write_all(b"// Generated by bubble-compiler\n// Type definitions for bubble-shell\n\n")?;
    out.write_all(hand_written.as_bytes())?;
    out.write_all(b"\n")?;
    out.write_all(generated.as_bytes())?;
    out.flush()
}
